def write_pdf():
    from reportlab.lib import colors
    from reportlab.lib.pagesizes import A4
    from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
    from reportlab.lib.units import cm
    from reportlab.platypus import (PageBreak, Paragraph, Preformatted, SimpleDocTemplate,
                                    Spacer, Table, TableStyle)

    styles = getSampleStyleSheet()
    body = ParagraphStyle("body", parent=styles["BodyText"], fontSize=9.5, leading=13)
    small = ParagraphStyle("small", parent=body, fontSize=7.2, leading=8.8)
    code = ParagraphStyle("code", fontName="Courier", fontSize=7, leading=8.5,
                          backColor=colors.HexColor("#F3F3F3"), borderPadding=4)
    h1, h2 = styles["Heading1"], styles["Heading2"]
    accent = colors.HexColor("#E4572E")

    def P(text, style=body):
        return Paragraph(text, style)

    def table(rows, widths, header=True, font=8):
        cell = ParagraphStyle("cell", parent=body, fontSize=font, leading=font + 2.5)
        head = ParagraphStyle("head", parent=cell, textColor=colors.white, fontName="Helvetica-Bold")
        wrapped = []
        for i, row in enumerate(rows):
            wrapped.append([Paragraph(escape(c), head if (header and i == 0) else cell)
                            if isinstance(c, str) else c for c in row])
        t = Table(wrapped, colWidths=widths, repeatRows=1 if header else 0)
        style = [("GRID", (0, 0), (-1, -1), 0.3, colors.grey), ("VALIGN", (0, 0), (-1, -1), "TOP"),
                 ("FONTSIZE", (0, 0), (-1, -1), font), ("LEFTPADDING", (0, 0), (-1, -1), 3),
                 ("RIGHTPADDING", (0, 0), (-1, -1), 3)]
        if header:
            style += [("BACKGROUND", (0, 0), (-1, 0), accent), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white)]
        t.setStyle(TableStyle(style))
        return t

    def footer(canvas, doc):
        canvas.saveState()
        canvas.setFont("Helvetica", 8)
        canvas.drawString(2 * cm, 1.2 * cm, "SOULSENSE - code explanation")
        canvas.drawRightString(A4[0] - 2 * cm, 1.2 * cm, f"Page {doc.page}")
        canvas.restoreState()

    s = []
    # ---------------------------------------------------------------- cover
    s += [Spacer(1, 4 * cm), P("SOULSENSE", ParagraphStyle("t", parent=styles["Title"], fontSize=34, textColor=accent)),
          P("Another Crab's Treasure Combat &amp; Build Advisor", styles["Heading2"]),
          P("A rule-based expert system with forward chaining, conflict resolution and an explanation facility. "
            "Code explanation: modules, rules, workflow, testing and deployment.", body),
          Spacer(1, 1 * cm),
          table([["Rules in the knowledge base", str(len(RULES))],
                 ["Rule categories", str(len(CATEGORIES))],
                 ["Derived (inferred) fact types", str(len(kb.DERIVED_FACTS))],
                 ["User-input facts", str(len(FACT_SCHEMA))],
                 ["Language / UI", "Python 3 / Streamlit"],
                 ["Inference method", "Forward chaining (match - resolve - act)"]],
                [7 * cm, 8 * cm], header=False, font=9),
          PageBreak()]

    # ----------------------------------------------------------- 1 overview
    s += [P("1. What the system does", h1),
          P("SOULSENSE is a rule-based expert system that advises players of <i>Another Crab's Treasure</i> on combat, "
            "shells, weapons and attacks, stat allocation, adaptations, healing and survival, boss preparation and "
            "defensive play. The player describes their situation through Streamlit forms. The inference engine "
            "evaluates those answers (facts) against the knowledge base (IF-THEN rules) and returns prioritised "
            "recommendations, each one explained by the rule that produced it."),
          Spacer(1, 6),
          P("It is a genuine expert system rather than a questionnaire: no answer is hard-coded to a response. "
            "Responses are the conclusions of rules, some of which depend on facts that other rules inferred. "
            "Machine learning is not used anywhere."),
          P("2. Architecture", h1),
          P("The classic expert-system components map one-to-one onto the code:"),
          table([["Component", "File", "Responsibility"],
                 ["Knowledge base", "knowledge_base/rules.py", "%d IF-THEN rules, thresholds, rule categories" % len(RULES)],
                 ["Fact vocabulary", "knowledge_base/facts.py", "Every user input with type, options and label"],
                 ["Evidence base", "knowledge_base/game_mechanics.md", "Verified mechanics M-01..M-24 cited by rules"],
                 ["Working memory", "engine/working_memory.py", "Stores user facts and inferred facts with their origin"],
                 ["Rule matcher", "engine/rule_matcher.py", "Evaluates AND / OR / NOT trees with 3-valued logic"],
                 ["Conflict resolver", "engine/conflict_resolver.py", "Priority, specificity, KB order; advice groups"],
                 ["Inference engine", "engine/inference_engine.py", "Forward-chaining loop, trace, missing-input analysis"],
                 ["Explanation facility", "components/result_display.py", "Shows fired rules, matched values, chains"],
                 ["User interface", "app.py, pages/, components/", "Streamlit pages, forms generated from the schema"]],
                [3.4 * cm, 5.3 * cm, 8.3 * cm]),
          Spacer(1, 8),
          Preformatted(
              "  Streamlit forms (components/input_forms.py)\n"
              "          |  answers (facts)                     \"Not sure\" = fact left out\n"
              "          v\n"
              "  +-----------------+     +----------------------+\n"
              "  | WORKING MEMORY  |<--->|  INFERENCE ENGINE    |<--- KNOWLEDGE BASE (rules)\n"
              "  | user + inferred |     |  match -> resolve -> |\n"
              "  | facts           |     |  act (repeat)        |\n"
              "  +-----------------+     +----------+-----------+\n"
              "                                     |  uses\n"
              "                       RULE MATCHER + CONFLICT RESOLVER\n"
              "                                     |\n"
              "                                     v\n"
              "      Recommendations + trace  -->  EXPLANATION FACILITY (UI)", code),
          PageBreak()]

    # --------------------------------------------------------- 3 modules
    s += [P("3. Module walk-through", h1),
          P("<b>working_memory.py</b> - class <font face='Courier'>WorkingMemory</font>. "
            "<font face='Courier'>assert_user_fact</font> stores a form answer (None, meaning 'not sure', is ignored). "
            "<font face='Courier'>assert_inferred</font> stores a rule conclusion and returns ADDED, UNCHANGED or BLOCKED. "
            "Memory is monotonic (facts are never removed or overwritten) which guarantees termination, and user facts "
            "always beat inferred ones."),
          P("<b>rule_matcher.py</b> - conditions are a small tree: <font face='Courier'>Cond(fact, operator, value)</font> "
            "leaves combined with <font face='Courier'>AllOf</font> (AND), <font face='Courier'>AnyOf</font> (OR) and "
            "<font face='Courier'>Not</font>. Operators: == != &lt; &lt;= &gt; &gt;= in, not in, contains, not contains, "
            "contains any, is true, is false, count ==, count &gt;=, count &lt;. Evaluation returns True, False or "
            "None (unknown) plus explanation lines that show the actual value of every fact tested."),
          P("<b>rule.py</b> - the <font face='Courier'>Rule</font> dataclass: id, category, name, conditions, priority, "
            "advice, asserts (inferred facts), severity, group, basis, sources and rationale."),
          P("<b>conflict_resolver.py</b> - ranks matched rules and resolves contradictory advice (section 5)."),
          P("<b>inference_engine.py</b> - class <font face='Courier'>InferenceEngine</font>; "
            "<font face='Courier'>run(user_facts)</font> executes forward chaining and returns an "
            "<font face='Courier'>InferenceResult</font> containing every firing, the recommendations, the overruled "
            "advice, rules that could not be evaluated and the final working memory."),
          P("<b>rule_analysis.py</b> - a small constraint solver that builds an input satisfying any rule. It proves "
            "that no rule is dead and supplies the 'example input' shown in the Knowledge Explorer."),
          P("<b>components/</b> - <font face='Courier'>session.py</font> (shared answers dictionary and engine access), "
            "<font face='Courier'>input_forms.py</font> (widgets generated from the fact schema), "
            "<font face='Courier'>result_display.py</font> (cards, traces, explanations), "
            "<font face='Courier'>navigation.py</font> (st.navigation registry)."),
          P("<b>pages/</b> - one module per screen, each exposing <font face='Courier'>render()</font>: home, profile, "
            "combat_advisor, shell_advisor, boss_advisor, progression_advisor, diagnosis, knowledge_explorer."),
          P("4. Forward chaining", h1),
          P("Forward chaining is data-driven: begin with known facts and keep firing rules until nothing new follows. "
            "Each cycle has three steps:"),
          P("<b>1. Match</b> - every rule that has not fired yet is evaluated; those whose conditions are TRUE form the "
            "<i>conflict set</i>.<br/><b>2. Resolve</b> - the conflict resolver picks one rule.<br/>"
            "<b>3. Act</b> - the rule fires: it asserts its inferred facts and/or records its advice. The loop repeats "
            "because new facts may make further rules match. It stops when the conflict set is empty. A rule can fire "
            "at most once (refraction), so the loop always terminates."),
          P("<b>Chaining example.</b> Rule SHL-01 (priority 100) infers <font face='Courier'>shell_condition = critical</font> "
            "from <font face='Courier'>shell_durability_pct &lt;= 30</font>. Only after that can SHL-04 match on "
            "<font face='Courier'>shell_condition == 'critical'</font> and advise swapping the shell. The explanation "
            "shows this dependency as 'Chain: uses conclusions of SHL-01'."),
          P("Worked trace of the scenario <i>Blocker with a cracking shell</i> (generated by the real engine):")]
    result = ENGINE.run(SCENARIOS["Blocker with a cracking shell"]["facts"])
    trace = "\n".join(f"cycle {f.cycle:2d}  {f.rule.id}  {f.rule.name[:38]:38}  won: {f.reason[:40]}"
                      + (f"  -> infers {f.asserted}" if f.asserted else "") for f in result.firings)
    s += [Preformatted("\n".join(textwrap.wrap(l, 118, subsequent_indent="           ")[0] if len(l) < 119 else
                                 "\n".join(textwrap.wrap(l, 118, subsequent_indent="              "))
                                 for l in trace.split("\n")), code),
          Spacer(1, 6),
          P("Full explanation of one recommendation as the system prints it:"),
          Preformatted("\n".join("\n".join(textwrap.wrap(l, 118, subsequent_indent="        ")) if l.strip() else l
                                 for l in result.explain("SHL-04").split("\n")), code),
          Spacer(1, 10)]

    # ------------------------------------------------- 5 conflict resolution
    s += [P("5. Conflict resolution", h1),
          P("Two kinds of conflict exist, so two documented strategies are used."),
          P("<b>Agenda conflict - which matched rule fires next?</b> The conflict set is sorted by "
            "(a) <b>priority</b>, higher first; (b) <b>specificity</b>, the number of elementary tests in the rule, "
            "higher first; (c) <b>position in the knowledge base</b>, earlier first. The reason that decided the "
            "choice is stored with every firing and displayed to the user."),
          P("Derivation rules use priority 100 so the facts they infer exist before advice rules are chosen. If two "
            "rules infer different values for the same fact, the first (higher-ranked) wins and the other is reported "
            "as 'blocked'."),
          P("<b>Recommendation conflict - contradictory advice.</b> Rules that answer the same question share a "
            "<i>group</i> (defense_mode, weight_choice, stat_priority, resource_action, heal_or_rest, boss_phase). "
            "Only the best-ranked advice of a group is shown as primary; the others appear under 'Advice overruled by "
            "conflict resolution' with the name of the winning rule, so nothing is hidden."),
          table([["Group", "Question answered", "Example resolution"],
                 ["defense_mode", "Block, dodge or parry?", "DEF-06 (conserve a worn shell, priority 65) overrules CMB-03 (block, 50)"],
                 ["stat_priority", "Which stat first?", "PRG-02 beats PRG-01 for veteran attackers: same priority, more specific"],
                 ["heal_or_rest", "Use a pod or rest at the Moon Snail Shell?", "SRV-06 (area already cleared, 72) overrules SRV-05 (70)"],
                 ["boss_phase", "Generic or live phase-two advice?", "BOS-03 (HP below 50 percent) overrules BOS-02"],
                 ["weight_choice", "Heavy or light shell?", "Mutually exclusive playstyles, ranked if both match"],
                 ["resource_action", "Spend or bank microplastics?", "Decided by whether a checkpoint is near"]],
                [3 * cm, 5 * cm, 9 * cm]),
          P("6. Handling missing or uncertain input", h1),
          P("Every form field offers 'Not sure'. Such an answer is not stored, so the fact is <b>unknown</b>. The matcher uses "
            "three-valued logic: AND is false if any part is false, unknown if any part is unknown, otherwise true; OR is "
            "true if any part is true, unknown if any part is unknown, otherwise false. A rule with an unknown condition "
            "simply does not fire, and the engine traces unknown derived facts (for example shell_condition) back to the "
            "user questions behind them. The UI then lists 'Answer more to unlock N rules' with the most useful questions "
            "first. Empty input never crashes the system."),
          PageBreak()]

    # --------------------------------------------------------------- 7 rules
    s += [P("7. Knowledge base", h1),
          P("Rules are grouped in eight categories. Evidence types: <b>mechanic</b> (follows from a verified game mechanic), "
            "<b>guide</b> (community-guide recommendation), <b>tactic</b> (general tactic applied to a mechanic), "
            "<b>design</b> (classification written by the designer, for example 'durability up to 30 percent is critical'). "
            "Threshold values are named constants at the top of rules.py and are not claimed to be game mechanics."),
          table([["Category", "Rules"]] + [[title, str(sum(1 for r in RULES if r.category == key))]
                                           for key, title in CATEGORIES.items()], [10 * cm, 3 * cm]),
          Spacer(1, 6),
          P("Where sources disagree (for example which stat to raise first) the knowledge base does not pick a side; it "
            "gives playstyle-specific advice. Where no verified boss mechanic exists, rule BOS-18 says so instead of "
            "inventing advice. Full evidence list: knowledge_base/game_mechanics.md.")]
    for key, title in CATEGORIES.items():
        rows = [["ID", "Rule / IF", "THEN", "P"]]
        for r in (x for x in RULES if x.category == key):
            then = ("Infers " + ", ".join(f"{k}={v}" for k, v in r.asserts.items()) + ". ") if r.asserts else ""
            then += r.advice or ""
            rows.append([P(r.id, small),
                         P(f"<b>{escape(r.name)}</b><br/>IF {escape(r.conditions.describe())}", small),
                         P(escape(then), small), P(str(r.priority), small)])
        s += [PageBreak(), P(f"7.{list(CATEGORIES).index(key) + 1}  {title}", h2),
              table(rows, [1.5 * cm, 6.3 * cm, 8.3 * cm, 0.9 * cm], font=7)]
    s.append(PageBreak())

    # ----------------------------------------------------------- 8 UI / flow
    s += [P("8. User interface and workflow", h1),
          table([["Page", "Purpose"],
                 ["Home", "Dashboard, rule counts, how it works, load an example player"],
                 ["Player profile", "Questionnaire shared by every advisor"],
                 ["Combat advisor", "Encounter-level tactics (combat, weapon and defense rules)"],
                 ["Shell and equipment", "Durability, weight, insurance, spells, stowaways"],
                 ["Boss preparation", "Boss-specific and phase advice"],
                 ["Progression and survival", "Stats, skills, economy, healing, hazards"],
                 ["Expert diagnosis", "All recommendations, forward-chaining trace, working memory, conflicts, every fired rule"],
                 ["Knowledge base", "Browse and search all rules, facts, verified mechanics; example input per rule"]],
                [4.5 * cm, 12.5 * cm]),
          Spacer(1, 6),
          P("Workflow: (1) widgets write answers into one shared dictionary in st.session_state; (2) an advisor page calls "
            "<font face='Courier'>run_engine()</font>, which runs forward chaining on that dictionary; (3) the result is "
            "rendered as cards sorted by severity, each with a 'Why this advice?' panel. Forms are generated from the fact "
            "schema, so adding a fact needs no new UI code. Using st.navigation turns off Streamlit's automatic pages/ "
            "scanning so the sidebar is exactly the structure registered in navigation.py."),
          P("9. Testing", h1),
          P("Tests use only the standard library (<font face='Courier'>python -m unittest discover -s tests -v</font>). "
            "Beyond ordinary unit tests, knowledge-base integrity tests catch mistakes automatically:"),
          table([["Test file", "What it proves"],
                 ["test_engine.py", "Memory rules, every operator, 3-valued logic, conflict ordering, group suppression, "
                                    "chaining across 2 and 3 steps, refraction, blocked inference, missing-input tracing"],
                 ["test_rules.py", "At least 50 rules, unique ids, every category populated, only known facts and valid option values "
                                   "used (typo guard), every derived fact is inferred by some rule, every cited mechanic exists, "
                                   "and every rule is reachable (an input is synthesised and the engine really fires the rule)"],
                 ["test_scenarios.py", "Six realistic players trigger the expected rules, conflicts resolve as documented, "
                                       "empty and partial input are handled"],
                 ["test_ui_smoke.py", "Every page renders for every scenario; forms do not alter stored answers; "
                                      "the app entry point and navigation load (AppTest when Streamlit is installed)"]],
                [3.5 * cm, 13.5 * cm]),
          P("10. Deployment (Streamlit Community Cloud)", h1),
          P("1. Create a public GitHub repository and push the project root (app.py at the top level).<br/>"
            "2. Open share.streamlit.io, sign in with GitHub, choose <i>Create app</i>.<br/>"
            "3. Select the repository, branch and set the main file path to <font face='Courier'>app.py</font>.<br/>"
            "4. Deploy. Dependencies are read from requirements.txt (streamlit only).<br/>"
            "5. Put the resulting public URL in README.md. Anyone on the internet can then open it."),
          P("11. Limitations and honesty", h1),
          P("The knowledge was compiled from published guides, reviews and patch notes, not from the game files. Some values "
            "come from a single source and are marked as such; sources sometimes disagree and the knowledge base says so. "
            "Patches may change numbers. The advisor cannot read the game screen, so it relies on honest answers. The tests "
            "check the knowledge base for internal consistency, not the truth of the game facts - that is what the evidence "
            "document is for."),
          P("12. Likely viva questions", h1),
          table([["Question", "Answer"],
                 ["Why is this an expert system, not an if-else script?", "Knowledge (rules) is separate from the inference "
                  "engine; rules are data, can chain, and the engine explains its reasoning."],
                 ["Why forward chaining?", "Facts arrive first (the player's situation) and we want every applicable "
                  "recommendation, which is data-driven reasoning. Backward chaining suits a single goal to prove."],
                 ["How are conflicts resolved?", "Priority, then specificity, then KB order; plus advice groups so only "
                  "one answer per question is primary."],
                 ["What happens with missing data?", "Three-valued logic: unknown conditions do not fire; the UI says which "
                  "answers would unlock more rules."],
                 ["How do you know rules are not dead?", "rule_analysis.py synthesises an input for each rule and a test "
                  "checks the engine fires it."],
                 ["How did you avoid inventing game mechanics?", "Every rule cites a verified mechanic id; unverified items are "
                  "left out or flagged; thresholds are labelled as designer heuristics."],
                 ["Does it terminate?", "Yes: monotonic memory and each rule fires at most once."]],
                [5.5 * cm, 11.5 * cm])]

    pdf_path = os.path.join(ROOT, "code_explanation.pdf")
    doc = SimpleDocTemplate(pdf_path, pagesize=A4, leftMargin=2 * cm, rightMargin=2 * cm,
                            topMargin=1.8 * cm, bottomMargin=1.8 * cm,
                            title="SOULSENSE - code explanation", author="SOULSENSE project")
    doc.build(s, onFirstPage=footer, onLaterPages=footer)
    return pdf_path


