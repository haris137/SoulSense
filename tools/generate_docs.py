def then_text(rule):
    parts = []
    if rule.asserts:
        parts.append("infer " + ", ".join(f"`{k} = {v}`" for k, v in rule.asserts.items()))
    if rule.advice:
        parts.append(rule.advice)
    return " **and** ".join(parts)


def write_rules_md():
    out = ["# SOULSENSE - Rule Catalogue", "",
           f"*Generated by `tools/generate_docs.py` from `knowledge_base/rules.py` - {len(RULES)} rules.*", "",
           "Legend: **P** = priority (higher fires first), **T** = number of tests (specificity), "
           "**Group** = rules that answer the same question (only the best advice is shown). "
           "**Evidence**: *mechanic* = verified game mechanic, *guide* = community-guide advice, "
           "*tactic* = general tactic on a verified mechanic, *design* = designer classification. "
           "Mechanic ids (M-xx) refer to `knowledge_base/game_mechanics.md`.", ""]
    for key, title in CATEGORIES.items():
        rules = [r for r in RULES if r.category == key]
        out += [f"## {title}  ({len(rules)} rules)", "",
                "| ID | Name | IF | THEN | P | T | Group | Evidence |",
                "|----|------|----|------|---|---|-------|----------|"]
        for r in rules:
            cond = r.conditions.describe().replace("|", "\\|")
            then = then_text(r).replace("|", "\\|")
            ev = r.basis + (f" ({', '.join(r.sources)})" if r.sources else "")
            out.append(f"| {r.id} | {r.name} | `{cond}` | {then} | {r.priority} | {r.specificity} | "
                       f"{r.group or '-'} | {ev} |")
        out.append("")
    out += ["## Inferred (derived) facts", "", "| Fact | Values | Inferred by |", "|------|--------|-------------|"]
    for fact, values in kb.DERIVED_FACTS.items():
        by = ", ".join(r.id for r in RULES if fact in r.asserts)
        out.append(f"| `{fact}` | {', '.join(map(str, values))} | {by} |")
    out += ["", "## Example inputs that fire each rule", "",
            "Produced automatically by `engine/rule_analysis.py` (a small constraint solver) and "
            "verified by `tests/test_rules.py::test_every_rule_is_reachable`.", ""]
    for r in RULES:
        example = synthesize_example(r, RULES, FACT_SCHEMA)
        out.append(f"- **{r.id}**: `{example}`")
    path = os.path.join(ROOT, "docs", "RULES.md")
    with open(path, "w", encoding="utf-8") as fh:
        fh.write("\n".join(out) + "\n")
    return path


